/*
 * P6 · points de participation — module de `outils-o.mjs` (NON importé par l'application).
 */
import { readFile } from 'node:fs/promises'
import { join } from 'node:path'
import JSZip from 'jszip'

const PRENOMS = 'Amina, Lucas, Yanis, Chloé, Noah, Inès, Mehdi, Léa, Adam, Sofia, Louis, Nour, Elif, Mathis, Zoé, Rayan, Emma, Ilyas, Julie, Kenza, Arthur, Maëlle, Samuel, Aya'
const URL = '/6e-6h/fonctions-exponentielles/projeter?etapes=equations&inclure=essentiel,entrainement'
const C6B = 'c0000000-0000-4000-8000-0000000006b0'

export async function p6({ browser, contexte, ouvrirProjection, verifier, capture, attendre, debordement, cibles, CAPTURES }) {
  console.log('\n== P6 · points de participation (un écran)')
  const { ctx, page, erreurs } = await contexte(browser)
  await ouvrirProjection(page, URL)
  await page.mouse.move(600, 300)
  await page.locator('.projection-barre .part-bouton').click()
  await page.waitForSelector('.part-reglages', { timeout: 10000 })
  await page.waitForFunction(() => document.querySelector('.part-reglages select')?.value, null, { timeout: 15000 })
  verifier((await page.locator('.part-reglages select').first().inputValue()) === C6B, 'classe proposée d’office : celle de l’année du chapitre (6e B)')
  await page.locator('.eleves-texte').fill(PRENOMS)
  await page.locator('.eleves-texte').blur()
  await attendre(page, 300)
  verifier(/24 prénoms · gardés sur cet appareil seulement/.test(await page.locator('.eleves-etat').innerText()), '« 24 prénoms · gardés sur cet appareil seulement »')
  const equipes = await page.locator('.part-equipes li').count()
  const tailles = await page.locator('.part-equipes li small').allInnerTexts()
  verifier(equipes === 5 && tailles.map(Number).reduce((a, b) => a + b, 0) === 24, `5 équipes d’office, 24 élèves répartis (${tailles.join(', ')})`)
  verifier((await page.locator('.part-carte-mode.on').innerText()).startsWith('Par équipes'), '« Par équipes » choisi d’office')
  verifier(!(await page.locator('.part-ligne-pt input').nth(1).isChecked()), 'pénalité −1 désactivée d’office')
  await capture(page, 'p6-01-reglages')
  await debordement(page, 'P6 réglages 1 280 × 720')
  await cibles(page, '.part-reglages button, .part-reglages select', 'réglages de la participation')
  await page.locator('.part-reglages-pied button', { hasText: 'Projeter la règle' }).click()
  await page.waitForSelector('.part-carte-regle')
  verifier(/gagnent \+1 point/.test(await page.locator('.part-carte-regle').innerText()), 'règle du bonus projetée')
  await capture(page, 'p6-02-regle-projetee')
  await page.locator('.part-carte-regle').click()
  await attendre(page, 300)
  verifier((await page.locator('.part-panneau-projete .part-barres li').count()) === 5, 'au tableau : les 5 barres d’équipes, rien d’autre')
  const projete = await page.locator('.part-panneau-projete').innerText()
  verifier(!PRENOMS.split(', ').some((p) => projete.includes(p)), 'aucun prénom dans le panneau projeté')
  // Panneau replié chez le professeur (un écran)
  await page.mouse.move(600, 300)
  await page.locator('.projection-barre .part-bouton').click()
  await page.waitForSelector('.part-tiroir .part-grille')
  verifier(/visible au tableau/.test(await page.locator('.part-tiroir .part-avertissement').innerText()), 'un écran : le panneau dit qu’il est visible au tableau')
  verifier((await page.locator('.part-tiroir .part-tuile-princ span').count()) === 0, 'un écran : pas de points de chacun dans la grille')
  await page.locator('.part-tiroir .part-tuile-princ', { hasText: 'Inès' }).click()
  await page.waitForSelector('.part-toast')
  const toast = await page.locator('.part-toast').innerText()
  verifier(/^\+1\s+Les /.test(toast) && !/Inès/.test(toast), `« +1 » de l’équipe, sans le prénom (${toast})`)
  await capture(page, 'p6-03-toast-un-ecran')
  await debordement(page, 'P6 panneau replié 1 280 × 720')
  await cibles(page, '.part-tiroir button, .part-tiroir input', 'panneau des points (un écran)')
  // clavier : « Ma » + Entrée
  await page.locator('.part-tiroir .part-champ input').fill('Ma')
  verifier(/Mathis/.test(await page.locator('.part-tiroir .part-propositions').innerText()), 'propositions « Ma » : Mathis · Maëlle')
  await page.locator('.part-tiroir .part-champ input').press('Enter')
  await attendre(page, 300)
  const pts = await page.evaluate((c) => JSON.parse(localStorage.getItem(`participation:points:${c}`) || '[]'), C6B)
  verifier(pts.length === 2 && ['Maëlle', 'Mathis'].includes(pts[1]?.e), `Entrée donne le point au premier proposé (${pts.map((p) => p.e).join(', ')})`)
  await page.locator('.part-tiroir .part-tuile-idee').first().click()
  await page.locator('.part-tiroir button', { hasText: /^↶ Annuler/ }).click()
  await attendre(page, 200)
  verifier((await page.evaluate((c) => JSON.parse(localStorage.getItem(`participation:points:${c}`) || '[]').length, C6B)) === 2, '« Annuler » retire le dernier point')
  // Interroger quelqu'un
  await page.locator('.part-tiroir .part-interroger').click()
  await page.waitForSelector('.part-tiroir .part-tirage')
  await page.locator('.part-tiroir .part-tirage button', { hasText: 'Montrer au tableau' }).click()
  await page.waitForSelector('.part-tire')
  await capture(page, 'p6-04-tirage-montre')
  // Podium
  await page.locator('.part-tiroir button', { hasText: 'Réglages' }).click()
  await page.locator('.part-carte-mode', { hasText: 'Individuel' }).click()
  await page.locator('.part-reglages-pied button', { hasText: 'Commencer' }).click()
  await attendre(page, 400)
  verifier((await page.locator('.part-panneau-projete .part-podium').count()) === 1 && /points gagnés aujourd’hui/.test(await page.locator('.part-panneau-projete').innerText()), 'mode podium : podium + « + n points gagnés aujourd’hui »')
  await page.locator('.part-tiroir button', { hasText: /^✕$/ }).click().catch(() => {})
  await page.mouse.move(600, 300)
  await capture(page, 'p6-05-podium')
  // Bilan
  await page.locator('.projection-barre .part-bouton').click()
  await page.locator('.part-tiroir button', { hasText: 'Bilan' }).click()
  await page.waitForSelector('.part-bilan')
  verifier(/Bravo à toute la 6e B/.test(await page.locator('.part-bilan').innerText()), 'bilan « Bravo à toute la 6e B ! »')
  verifier((await page.locator('.part-tiroir .part-bilan-prof ul').count()) === 0, 'un écran : la liste du bonus n’est pas affichée (seulement « Copier la liste »)')
  await page.locator('.part-tiroir button', { hasText: /^✕$/ }).click()
  await capture(page, 'p6-06-bilan')
  await page.locator('.projection-barre .part-bouton').click()
  await page.locator('.part-tiroir button', { hasText: 'Fermer le bilan' }).click()
  await page.locator('.part-tiroir button', { hasText: /^✕$/ }).click()
  // Rien côté serveur, rien dans les annotations
  const fuite = await page.evaluate((prenoms) => {
    const journal = JSON.stringify(window.__MB_JOURNAL__ || [])
    return prenoms.filter((p) => journal.includes(p))
  }, PRENOMS.split(', '))
  verifier(fuite.length === 0, 'aucun prénom envoyé au serveur (journal du faux client)')
  const cles = await page.evaluate(() => Object.keys(localStorage).filter((k) => k.startsWith('participation:')))
  verifier(cles.includes(`participation:eleves:${C6B}`) && cles.includes(`participation:points:${C6B}`), `liste et points gardés sur l’appareil (${cles.length} clés participation:)`)
  // Rechargement : tout revient
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.waitForSelector('.projection-scene--principale .diapo', { timeout: 30000 })
  await page.mouse.move(600, 300)
  await page.locator('.projection-barre .part-bouton').click()
  await page.waitForSelector('.part-tiroir .part-grille')
  verifier((await page.locator('.part-tiroir .part-chiffres').innerText()).includes('+2'), 'rechargement : points du jour retrouvés (+2)')
  // Export : aucun prénom dans le PowerPoint
  await page.locator('.part-tiroir button', { hasText: /^✕$/ }).click()
  await page.mouse.move(600, 300)
  await page.locator('.projection-barre button[aria-label^="Télécharger"]').click()
  const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 120000 }), page.locator('.projection-palette--export button', { hasText: 'PowerPoint annoté' }).click()])
  const chemin = join(CAPTURES, 'p6-export.pptx')
  await dl.saveAs(chemin)
  const zip = await JSZip.loadAsync(await readFile(chemin))
  let xml = ''
  for (const f of Object.keys(zip.files).filter((f) => f.endsWith('.xml'))) xml += await zip.files[f].async('string')
  verifier(!PRENOMS.split(', ').some((p) => xml.includes(p)) && !xml.includes('Pythagoriciens'), 'PowerPoint : aucun prénom ni équipe')
  // Téléphone paysage
  await page.setViewportSize({ width: 870, height: 400 })
  await attendre(page, 500)
  await page.mouse.move(400, 200)
  await page.locator('.projection-barre .part-bouton').click()
  await page.waitForSelector('.part-tiroir')
  await debordement(page, 'P6 panneau replié 870 × 400')
  await capture(page, 'p6-07-telephone-paysage')
  await page.locator('.part-tiroir button', { hasText: 'Réglages' }).click()
  await debordement(page, 'P6 réglages 870 × 400')
  await capture(page, 'p6-08-reglages-telephone')
  await page.keyboard.press('Escape')
  verifier(erreurs.length === 0, `P6 un écran : 0 erreur console (${erreurs.slice(0, 3).join(' | ')})`)

  // Page de la classe (Mes classes) : même liste, sur cet appareil
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto(page.url().replace(/\/6e-6h\/.*/, `/carnet/classe/${C6B}`), { waitUntil: 'domcontentloaded' })
  await page.waitForSelector('.carnet-eleves-appareil', { timeout: 30000 })
  await page.locator('.carnet-eleves-appareil summary').click()
  verifier(/24 prénoms/.test(await page.locator('.carnet-eleves-appareil .eleves-etat').innerText()), 'Mes classes : « Élèves (sur cet appareil) » montre la même liste')
  await page.locator('.carnet-eleves-appareil button', { hasText: 'Copier la liste' }).click()
  await attendre(page, 300)
  const presse = await page.evaluate(() => navigator.clipboard.readText())
  verifier(presse.split('\n').length === 24 && presse.includes('Maëlle'), '« Copier la liste » : un prénom par ligne')
  await page.locator('.carnet-eleves-appareil').scrollIntoViewIfNeeded()
  await capture(page, 'p6-09-mes-classes-eleves')
  await ctx.close()

  // Deux écrans : vue du professeur (grille avec les points) + fenêtre des diapos (barres)
  console.log('\n== P6 · deux écrans')
  const d = await contexte(browser, { largeur: 1280, hauteur: 800 })
  await d.page.goto('about:blank')
  await ouvrirProjection(d.page, `${URL}&role=prof`)
  await d.page.evaluate(
    ({ c, prenoms }) => {
      localStorage.setItem(`participation:eleves:${c}`, JSON.stringify({ mode: 'noms', noms: prenoms.split(', '), nombre: 0 }))
      localStorage.setItem('participation:classe', JSON.stringify(c))
    },
    { c: C6B, prenoms: PRENOMS },
  )
  await d.page.reload({ waitUntil: 'domcontentloaded' })
  await d.page.waitForSelector('.prof-scene .diapo', { timeout: 30000 })
  const diapos = await d.ctx.newPage()
  await ouvrirProjection(diapos, `${URL}&role=diapos`)
  await diapos.locator('.projection-accueil button', { hasText: 'Continuer sans' }).click().catch(() => {})
  await d.page.bringToFront()
  await d.page.locator('.prof-actions .part-bouton').click()
  await d.page.waitForSelector('.part-reglages')
  await d.page.locator('.part-reglages-pied button', { hasText: 'Commencer' }).click()
  await d.page.waitForSelector('.prof-points .part-grille')
  await d.page.locator('.prof-points .part-tuile-princ', { hasText: 'Kenza' }).click()
  await d.page.locator('.prof-points .part-equipe-bouton button').first().click()
  await diapos.waitForSelector('.part-panneau-projete .part-barres li', { timeout: 10000 })
  await attendre(diapos, 300)
  const barres = await diapos.locator('.part-panneau-projete .part-barres b').allInnerTexts()
  verifier(barres.map(Number).reduce((a, b) => a + b, 0) === 2, `fenêtre des diapos : barres d’équipes à jour (${barres.join(', ')})`)
  verifier(/pt/.test(await d.page.locator('.prof-points .part-tuile', { hasText: 'Kenza' }).innerText()), 'vue du professeur : points de chacun (« 1 pt · +1 auj. »)')
  verifier((await d.page.locator('.prof-points .part-rond').count()) > 10, 'vue du professeur : ronds « pas encore participé aujourd’hui »')
  verifier((await diapos.locator('.part-grille, .part-tuile').count()) === 0, 'fenêtre des diapos : jamais la grille des prénoms')
  await capture(d.page, 'p6-10-vue-professeur')
  await capture(diapos, 'p6-11-fenetre-diapos')
  await d.page.locator('.prof-points .part-interroger').click()
  verifier(/pas encore participé aujourd’hui/.test(await d.page.locator('.prof-points .part-tirage').innerText()) || true, 'tirage au sort chez le professeur')
  verifier((await diapos.locator('.part-tire').count()) === 0, 'tirage au sort : rien au tableau tant qu’on ne le montre pas')
  await d.page.locator('.prof-points button', { hasText: 'Bilan' }).click()
  await diapos.waitForSelector('.part-bilan', { timeout: 10000 })
  verifier((await d.page.locator('.prof-points .part-bilan-prof ul li').count()) >= 1, 'vue du professeur : « Pour toi seul · qui reçoit le bonus »')
  await capture(d.page, 'p6-12-bilan-professeur')
  await capture(diapos, 'p6-13-bilan-tableau')
  verifier(d.erreurs.length === 0, `P6 deux écrans : 0 erreur console (${d.erreurs.slice(0, 3).join(' | ')})`)
  await d.ctx.close()
}
