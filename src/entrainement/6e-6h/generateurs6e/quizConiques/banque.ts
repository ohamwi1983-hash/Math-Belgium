import type { FragmentConsigne, QuestionVraiFaux, VarianteQuizConiques } from "../../core6e/quizConiques.types";

const R = String.raw;

/** Découpe « texte $formule$ texte » en fragments (les « $ » ne servent qu'à délimiter). */
function fragments(source: string): FragmentConsigne[] {
  return source
    .split("$")
    .map((morceau, i): FragmentConsigne => (i % 2 === 1 ? { type: "latex", valeur: morceau } : { type: "texte", valeur: morceau }))
    .filter((f) => f.valeur !== "");
}

function q(enonce: string, reponse: boolean, justification: string): QuestionVraiFaux {
  return { enonce: fragments(enonce), reponse, justification: fragments(justification) };
}

